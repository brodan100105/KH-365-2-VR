#!/usr/bin/env python3
"""Renders printable ASCII (32..126) of a monospace TTF into an 8-bit alpha atlas header for the
in-headset UI (core/src/font_data.h).

    python3 tools/gen_font.py /usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf

The default font is DejaVu Sans Mono (Bitstream Vera license, which allows embedding the glyphs).
"""
import sys
from PIL import Image, ImageDraw, ImageFont

CELL_W, CELL_H, SIZE = 10, 20, 16
OUT = "core/src/font_data.h"


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
    font = ImageFont.truetype(path, SIZE)
    ascent, _ = font.getmetrics()
    glyphs = []
    for code in range(32, 127):
        img = Image.new("L", (CELL_W, CELL_H), 0)
        ImageDraw.Draw(img).text((0, (CELL_H - SIZE) // 2 + SIZE - ascent - 1), chr(code), fill=255, font=font)
        glyphs.append(list(img.tobytes()))
    with open(OUT, "w") as f:
        f.write("// Generated by tools/gen_font.py from DejaVu Sans Mono (Bitstream Vera license).\n")
        f.write("// Printable ASCII 32..126, one %dx%d 8-bit alpha cell per glyph, rows top to bottom.\n" % (CELL_W, CELL_H))
        f.write("#pragma once\n#include <cstdint>\n\n")
        f.write("constexpr int kFontCellW = %d, kFontCellH = %d, kFontFirst = 32, kFontCount = %d;\n" % (CELL_W, CELL_H, len(glyphs)))
        f.write("static const uint8_t kFontAlpha[%d] = {\n" % (len(glyphs) * CELL_W * CELL_H))
        for g in glyphs:
            f.write(",".join(str(v) for v in g) + ",\n")
        f.write("};\n")


if __name__ == "__main__":
    main()
